CREATE TABLE professionals (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL,
    specialty VARCHAR(100)
);

CREATE TABLE working_hours (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id BIGINT      NOT NULL REFERENCES professionals (id) ON DELETE CASCADE,
    day_of_week     VARCHAR(10) NOT NULL,
    start_time      TIME        NOT NULL,
    end_time        TIME        NOT NULL,
    CHECK (start_time < end_time)
);

CREATE TABLE services (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)   NOT NULL,
    duration_minutes INT            NOT NULL CHECK (duration_minutes > 0),
    price            NUMERIC(10, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE appointments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id     BIGINT       NOT NULL REFERENCES professionals (id),
    service_id          BIGINT       NOT NULL REFERENCES services (id),
    customer_name       VARCHAR(100) NOT NULL,
    customer_phone      VARCHAR(20)  NOT NULL,
    start_at            TIMESTAMP    NOT NULL,
    end_at              TIMESTAMP    NOT NULL,
    status              VARCHAR(10)  NOT NULL,
    cancellation_reason VARCHAR(255),
    CHECK (start_at < end_at)
);

-- Cobre a busca de conflitos e a agenda do dia de um profissional.
CREATE INDEX idx_appointments_professional_start ON appointments (professional_id, start_at);
